    <h1>Privacy Verklaring</h1>

    <p>Bij installatiebedrijf Stassen nemen we de privacy van onze gebruikers serieus en zetten we ons in om hun persoonsgegevens te beschermen. 
        In deze privacyverklaring leggen we uit hoe we omgaan met de persoonlijke gegevens die we verzamelen wanneer je ons contactformulier invult en gebruik maakt van reCAPTCHA op onze website.</p>

    <h2>1. Gegevens die we verzamelen</h2>
    <p>Wanneer je het contactformulier invult, verzamelen we de volgende persoonsgegevens:</p>
    <ul>
        <li>Naam: Je volledige naam.</li>
        <li>E-mailadres: Je e-mailadres waarmee we contact met je kunnen opnemen.</li>
        <li>Adres: Je adresgegevens.</li>
        <li>Postcode: Je postcode.</li>
        <li>Bericht: De boodschap die je aan ons stuurt.</li>
    </ul>
    <p>Daarnaast wordt er ook een reCAPTCHA uitgevoerd om te verifiëren dat de inzending afkomstig is van een mens en geen geautomatiseerd proces. Dit proces verzamelt de volgende gegevens:</p>
    <ul>
        <li>g-recaptcha-response: De bevestiging die je doet door de reCAPTCHA-checkbox aan te vinken om te verifiëren dat je geen geautomatiseerd systeem bent.</li>
    </ul>

    <h2>2. Doelen van gegevensverwerking</h2>
    <p>We verwerken je gegevens voor de volgende doeleinden:</p>
    <ul>
        <li>Om je bericht te ontvangen en te beantwoorden.</li>
        <li>Om je gegevens op te slaan voor administratieve doeleinden, zoals het bijhouden van je verzoeken in onze database. Let op: alleen je bericht wordt opgeslagen in de database, geen persoonlijke gegevens zoals je naam, e-mailadres of adres.</li>
        <li>Om te zorgen voor de beveiliging van onze website en het voorkomen van misbruik via de reCAPTCHA.</li>
        <li>Om je te informeren of op andere wijze te communiceren met betrekking tot je aanvraag of bericht.</li>
    </ul>

    <h2>3. Opslag van gegevens</h2>
    <p>Je bericht wordt opgeslagen in onze database voor een periode die noodzakelijk is om te voldoen aan de bovengenoemde doeleinden. Persoonlijke gegevens zoals je naam, e-mailadres en adres worden niet opgeslagen. We nemen passende technische en organisatorische maatregelen om je bericht veilig op te slaan en ongeautoriseerde toegang of verlies te voorkomen.</p>

    <h2>4. Gegevens delen met derden</h2>
    <p>We delen je gegevens niet met derden, behalve in de volgende gevallen:</p>
    <ul>
        <li>Wanneer we wettelijk verplicht zijn om je gegevens te delen.</li>
        <li>Wanneer derden (zoals onze e-mailserviceprovider) betrokken zijn bij de technische uitvoering van onze diensten, maar deze derden mogen je gegevens uitsluitend gebruiken voor het doel waarvoor ze zijn verstrekt en moeten voldoen aan onze privacyvoorwaarden.</li>
    </ul>

    <h2>5. Gebruik van reCAPTCHA</h2>
    <p>Onze website maakt gebruik van reCAPTCHA om te controleren of je een mens bent en geen geautomatiseerd systeem. Dit wordt gedaan om spam en misbruik van ons contactformulier te voorkomen. De reCAPTCHA-service verzamelt gegevens over je gebruik van onze website, waaronder je IP-adres, het type browser, het besturingssysteem en mogelijk andere gegevens die door Google worden gebruikt voor analyse- en beveiligingsdoeleinden. Het gebruik van reCAPTCHA valt onder het privacybeleid en de gebruiksvoorwaarden van Google.</p>
    <p>Voor meer informatie over hoe Google je gegevens gebruikt, kun je hun <a href="https://policies.google.com/privacy" target="_blank">Privacybeleid</a> en <a href="https://policies.google.com/terms" target="_blank">Gebruiksvoorwaarden</a> raadplegen.</p>

    <h2>6. Jouw rechten</h2>
    <p>Je hebt altijd het recht om:</p>
    <ul>
        <li>Je persoonlijke gegevens in te zien.</li>
        <li>Je gegevens te corrigeren als ze onjuist of verouderd zijn.</li>
        <li>Je gegevens te laten verwijderen wanneer ze niet langer nodig zijn voor de doeleinden waarvoor ze zijn verzameld.</li>
    </ul>
    <p>Als je gebruik wilt maken van een van deze rechten, kun je contact met ons opnemen via info@stassen-installatie.nl.</p>

    <h2>7. Beveiliging</h2>
    <p>We nemen passende maatregelen om je persoonsgegevens te beschermen tegen verlies, misbruik en ongeautoriseerde toegang. Ondanks onze inspanningen kunnen we echter niet garanderen dat de gegevens altijd 100% veilig zijn, aangezien geen enkel systeem volledig beveiligd is.</p>

    <h2>8. Wijzigingen in deze privacyverklaring</h2>
    <p>We behouden ons het recht voor om deze privacyverklaring van tijd tot tijd bij te werken. Wanneer we wijzigingen aanbrengen, zullen we deze op deze pagina plaatsen met een bijgewerkte datum. We raden je aan deze verklaring regelmatig te controleren om op de hoogte te blijven van eventuele wijzigingen.</p>

    <h2>9. Contactinformatie</h2>
    <p>Als je vragen hebt over deze privacyverklaring of onze omgang met je persoonsgegevens, neem dan contact met ons op via:</p>
